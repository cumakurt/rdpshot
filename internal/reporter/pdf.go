const (
	pdfFontFamily     = "Helvetica"
	pdfReportTitle    = "RDP Security Assessment Report"
	pdfPageAlias      = "{nb}"
	pdfPageMarginMm   = 15.0
	pdfBottomMarginMm = 18.0
	pdfCellMarginMm   = 1.0
	pdfUsableWidthMm  = 180.0 // A4 width minus both side margins
	pdfTableLineHMm   = 5.0
	pdfHeadingLineHMm = 5.5
	pdfBodyLineHMm    = 5.5
)

// pdfColumn describes one cell of a wrapped table row.
type pdfColumn struct {
	Text  string
	Width float64
	Align string
}

// PDF writes a management-style PDF report.
func PDF(w io.Writer, d Data) error {
	doc := fpdf.New("P", "mm", "A4", "")
	doc.SetMargins(pdfPageMarginMm, pdfPageMarginMm, pdfPageMarginMm)
	doc.SetAutoPageBreak(true, pdfBottomMarginMm)
	doc.SetCellMargin(pdfCellMarginMm)
	doc.SetTitle(pdfReportTitle, false)
	doc.SetAuthor(about.Developer, false)
	doc.SetCreator(toolName, false)
	doc.AliasNbPages(pdfPageAlias)

	headerRight := orDash(d.Scan.Name) + " (" + orDash(d.Scan.ID) + ")"
	footerLabel := "Generated by " + toolName
	if d.ToolVersion != "" {
		footerLabel += " " + d.ToolVersion
	}
	footerLabel += " · " + about.Developer
	footerLabel += " | Page %d of " + pdfPageAlias

	doc.SetHeaderFunc(func() { pdfPageHeader(doc, headerRight) })
	doc.SetFooterFunc(func() {
		pdfPageFooter(doc, fmt.Sprintf(footerLabel, doc.PageNo()))
	})

	doc.AddPage()
	pdfTitleBlock(doc, d)
	pdfMetadataTable(doc, d)
	pdfExecutiveSummary(doc, d)

	doc.AddPage()
	pdfSeverityTable(doc, d)
	pdfComplianceMatrixSection(doc, d)
	pdfFindingsTable(doc, d)
	pdfRemediationSection(doc, d)
	pdfScreenshotsSection(doc, d)

	if err := doc.Error(); err != nil {
		return fmt.Errorf("build pdf report: %w", err)
	}
	if err := doc.Output(w); err != nil {
		return fmt.Errorf("write pdf report: %w", err)
	}
	return nil
}

// pdfPageHeader renders the running title and scan label on every page.
func pdfPageHeader(doc *fpdf.Fpdf, rightText string) {
	doc.SetFont(pdfFontFamily, "B", 9)
	doc.SetTextColor(44, 62, 80)
	doc.CellFormat(pdfUsableWidthMm/2, 6, pdfText(pdfReportTitle), "", 0, "L", false, 0, "")
	doc.SetFont(pdfFontFamily, "", 8)
	doc.SetTextColor(120, 120, 120)
	doc.CellFormat(pdfUsableWidthMm/2, 6, pdfText(rightText), "", 1, "R", false, 0, "")
	doc.SetDrawColor(200, 200, 200)
	doc.SetLineWidth(0.2)
	doc.Line(pdfPageMarginMm, doc.GetY(), pdfPageMarginMm+pdfUsableWidthMm, doc.GetY())
	doc.Ln(4)
}

// pdfPageFooter renders the generator label and page number.
func pdfPageFooter(doc *fpdf.Fpdf, label string) {
	doc.SetY(-12)
	doc.SetFont(pdfFontFamily, "I", 8)
	doc.SetTextColor(120, 120, 120)
	doc.CellFormat(0, 6, pdfText(label), "", 0, "C", false, 0, "")
}

// pdfTitleBlock renders the report title and scan subtitle on page 1.
func pdfTitleBlock(doc *fpdf.Fpdf, d Data) {
	if logo := strings.TrimSpace(d.Branding.LogoDataURI); strings.HasPrefix(logo, "data:image/") {
		pdfEmbedLogo(doc, logo)
	}
	doc.SetFont(pdfFontFamily, "B", 20)
	doc.SetTextColor(33, 47, 61)
	doc.CellFormat(0, 12, pdfText(pdfReportTitle), "", 1, "L", false, 0, "")
	subtitle := orDash(d.Scan.Name) + " (" + orDash(d.Scan.ID) + ")"
	doc.SetFont(pdfFontFamily, "", 11)
	doc.SetTextColor(100, 100, 100)
	doc.CellFormat(0, 8, pdfText(subtitle), "", 1, "L", false, 0, "")
	doc.Ln(4)
}

func pdfEmbedLogo(doc *fpdf.Fpdf, dataURI string) {
	comma := strings.Index(dataURI, ",")
	if comma < 0 {
		return
	}
	meta := dataURI[:comma]
	raw, err := base64.StdEncoding.DecodeString(dataURI[comma+1:])
	if err != nil || len(raw) == 0 {
		return
	}
	opts := fpdf.ImageOptions{ReadDpi: true}
	switch {
	case strings.Contains(meta, "image/png"):
		opts.ImageType = "PNG"
	case strings.Contains(meta, "image/jpeg"), strings.Contains(meta, "image/jpg"):
		opts.ImageType = "JPG"
	default:
		return
	}
	info := doc.RegisterImageOptionsReader("brandlogo", opts, bytes.NewReader(raw))
	if info == nil || doc.Error() != nil {
		return
	}
	doc.ImageOptions("brandlogo", pdfPageMarginMm, doc.GetY(), 36, 0, false, opts, 0, "")
	doc.Ln(22)
}

// pdfMetadataTable renders the scan metadata label/value table.
func pdfMetadataTable(doc *fpdf.Fpdf, d Data) {
	pdfSectionHeading(doc, "Scan Metadata")
	rows := [][2]string{
		{"Organization", orDash(d.Branding.Organization)},
		{"Engagement", orDash(firstNonEmpty(d.Branding.Engagement, d.Scan.Engagement))},
		{"Prepared By", orDash(d.Branding.PreparedBy)},
		{"Scan Name", orDash(d.Scan.Name)},
		{"Scan ID", orDash(d.Scan.ID)},
		{"Status", orDash(string(d.Scan.Status))},
		{"Started", orDash(formatTimePtr(d.Scan.StartedAt))},
		{"Finished", orDash(formatTimePtr(d.Scan.FinishedAt))},
		{"Scope Targets", orDash(scopeText(d.Scan))},
		{"Generated At", orDash(formatTime(d.GeneratedAt))},
		{"Tool Version", orDash(d.ToolVersion)},
	}
	if note := strings.TrimSpace(d.Branding.FooterNote); note != "" {
		rows = append(rows, [2]string{"Note", note})
	}
	doc.SetFont(pdfFontFamily, "", 8)
	doc.SetTextColor(45, 45, 45)
	for _, row := range rows {
		pdfTableRow(doc, []pdfColumn{
			{Text: row[0], Width: 50},
			{Text: row[1], Width: pdfUsableWidthMm - 50},
		}, pdfTableLineHMm, false)
	}
	doc.Ln(4)
}

// pdfExecutiveSummary renders the summary counters.
func pdfExecutiveSummary(doc *fpdf.Fpdf, d Data) {
	pdfSectionHeading(doc, "Executive Summary")
	doc.SetFont(pdfFontFamily, "", 8)
	doc.SetTextColor(45, 45, 45)
	extra := computeExecutiveExtras(d)
	critical := d.Summary.CountBySeverity(model.SeverityCritical)
	rows := [][2]string{
		{"Hardening Score", fmt.Sprintf("%d (%s)", d.HardeningScore, orDash(d.HardeningGrade))},
		{"Hosts Total", fmt.Sprintf("%d", d.Summary.HostsTotal)},
		{"Hosts Open", fmt.Sprintf("%d", d.Summary.HostsOpen)},
		{"NLA Coverage %", fmt.Sprintf("%d", extra.NLACoveragePct)},
		{"Open Findings", fmt.Sprintf("%d", extra.OpenVulnerable)},
		{"Hosts Auth Audited", fmt.Sprintf("%d", extra.HostsAudited)},
		{"Auth Skipped (no CredSSP)", fmt.Sprintf("%d", extra.AuthSkippedNoNLA)},
		{"Critical Findings", fmt.Sprintf("%d", critical)},
		{"Findings Total", fmt.Sprintf("%d", d.Summary.FindingsTotal)},
	}
	for _, bucket := range severityBuckets(d) {
		rows = append(rows, [2]string{"Findings " + bucket.Severity, fmt.Sprintf("%d", bucket.Count)})
	}
	rows = append(rows,
		[2]string{"Credentials Found", fmt.Sprintf("%d", d.Summary.CredsTotal)},
		[2]string{"Screenshots", fmt.Sprintf("%d", len(reportScreens(d.Screens)))},
	)
	top := 0
	for _, f := range sortedFindings(d.Findings) {
		if f.Status != model.FindingVulnerable && f.Status != model.FindingPotential {
			continue
		}
		top++
		rows = append(rows, [2]string{
			fmt.Sprintf("Top finding %d", top),
			string(f.Severity) + ": " + f.Title + " @ " + f.Address,
		})
		if top >= 3 {
			break
		}
	}
	for _, row := range rows {
		pdfTableRow(doc, []pdfColumn{
			{Text: row[0], Width: 50},
			{Text: row[1], Width: pdfUsableWidthMm - 50},
		}, pdfTableLineHMm, false)
	}
	doc.Ln(4)
}


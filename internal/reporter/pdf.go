// pdfTableHeader renders the styled header row of a table.
func pdfTableHeader(doc *fpdf.Fpdf, cols []pdfColumn, lineH float64) {
	doc.SetFont(pdfFontFamily, "B", 8)
	doc.SetTextColor(255, 255, 255)
	doc.SetFillColor(41, 128, 185)
	pdfTableRow(doc, cols, lineH, true)
	doc.SetTextColor(45, 45, 45)
	doc.SetFont(pdfFontFamily, "", 8)
}

// pdfTableRow renders one wrapped table row. Cells are padded to a common line
// count so their borders line up, and the row moves to a fresh page before it
// is drawn when it would cross the bottom margin.
func pdfTableRow(doc *fpdf.Fpdf, cols []pdfColumn, lineH float64, fill bool) {
	texts := make([]string, len(cols))
	counts := make([]int, len(cols))
	maxLines := 1
	for i, col := range cols {
		lines := pdfWrapLines(doc, pdfText(col.Text), col.Width)
		counts[i] = len(lines)
		if len(lines) > maxLines {
			maxLines = len(lines)
		}
		texts[i] = strings.Join(lines, "\n")
	}
	rowH := float64(maxLines) * lineH
	if doc.GetY()+rowH > pdfBreakY(doc) {
		doc.AddPage()
	}
	x0 := doc.GetX()
	y0 := doc.GetY()
	x := x0
	for i, col := range cols {
		align := col.Align
		if align == "" {
			align = "L"
		}
		doc.SetXY(x, y0)
		// Shorter cells get blank padding lines so every cell border reaches
		// the full row height.
		doc.MultiCell(col.Width, lineH, texts[i]+strings.Repeat("\n ", maxLines-counts[i]), "1", align, fill)
		x += col.Width
	}
	doc.SetXY(x0, y0+rowH)
}

// pdfBreakY returns the vertical position where automatic page breaks trigger.
func pdfBreakY(doc *fpdf.Fpdf) float64 {
	_, height := doc.GetPageSize()
	_, bottom := doc.GetAutoPageBreak()
	return height - bottom
}

// pdfWrapLines breaks text into lines that fit the given width. Wrapping is
// computed with the same core-font metrics MultiCell applies, so MultiCell
// renders each line as-is and row heights stay predictable.
func pdfWrapLines(doc *fpdf.Fpdf, text string, width float64) []string {
	text = strings.TrimRight(text, "\n")
	limit := width - 2*doc.GetCellMargin()
	var lines []string
	for _, para := range strings.Split(text, "\n") {
		lines = append(lines, wrapParagraph(doc, para, limit)...)
	}
	if len(lines) == 0 {
		lines = []string{""}
	}
	return lines
}

// wrapParagraph breaks one paragraph into lines no wider than limit. Breaking
// prefers spaces and falls back to hard breaks for unbreakable words; content
// is preserved except for the single space dropped at each wrap point, which
// matches MultiCell's own wrapping behavior.
func wrapParagraph(doc *fpdf.Fpdf, para string, limit float64) []string {
	if para == "" {
		return []string{""}
	}
	var lines []string
	start := 0
	lastSpace := -1
	width := 0.0
	for i := 0; i < len(para); i++ {
		charWidth := doc.GetStringWidth(para[i : i+1])
		if width+charWidth > limit && i > start {
			if lastSpace > start {
				lines = append(lines, para[start:lastSpace])
				start = lastSpace + 1
			} else {
				lines = append(lines, para[start:i])
				start = i
			}
			lastSpace = -1
			width = 0
			i = start - 1
			continue
		}
		width += charWidth
		if para[i] == ' ' {
			lastSpace = i
		}
	}
	lines = append(lines, para[start:])
	return lines
}

// pdfText converts arbitrary Unicode text to the Windows-1252 byte encoding
// used by fpdf's built-in core fonts. Runes without a Windows-1252 equivalent
// become '?' so measurement and rendering never leave the font's 256-byte
// range and non-Latin input cannot break document generation.
func pdfText(s string) string {
	s = strings.ReplaceAll(s, "\r\n", "\n")
	s = strings.ReplaceAll(s, "\r", "\n")
	var b strings.Builder
	b.Grow(len(s))
	for _, r := range s {
		b.WriteByte(pdfRune(r))
	}
	return b.String()
}

// pdfRune maps one rune to its Windows-1252 byte, or '?' when unrepresentable.
func pdfRune(r rune) byte {
	switch r {
	case '\n':
		return '\n'
	case '\t', ' ':
		return ' '
	case 0x20AC: // euro sign
		return 0x80
	case 0x201A: // single low quote
		return 0x82
	case 0x0192: // latin small f with hook
		return 0x83
	case 0x201E: // double low quote
		return 0x84
	case 0x2026: // ellipsis
		return 0x85
	case 0x2020: // dagger
		return 0x86
	case 0x2021: // double dagger
		return 0x87
	case 0x02C6: // modifier letter circumflex
		return 0x88
	case 0x2030: // per mille
		return 0x89
	case 0x0160: // latin capital s with caron
		return 0x8A
	case 0x2039: // single left angle quote
		return 0x8B
	case 0x0152: // latin capital ligature oe
		return 0x8C
	case 0x017D: // latin capital z with caron
		return 0x8E
	case 0x2018: // left single quote
		return 0x91
	case 0x2019: // right single quote
		return 0x92
	case 0x201C: // left double quote
		return 0x93
	case 0x201D: // right double quote
		return 0x94
	case 0x2022: // bullet
		return 0x95
	case 0x2013: // en dash
		return 0x96
	case 0x2014: // em dash
		return 0x97
	case 0x02DC: // small tilde
		return 0x98
	case 0x2122: // trade mark
		return 0x99
	case 0x0161: // latin small s with caron
		return 0x9A
	case 0x203A: // single right angle quote
		return 0x9B
	case 0x0153: // latin small ligature oe
		return 0x9C
	case 0x017E: // latin small z with caron
		return 0x9E
	case 0x0178: // latin capital y with diaeresis
		return 0x9F
	}
	if (r >= 0x20 && r <= 0x7E) || (r >= 0xA0 && r <= 0xFF) {
		return byte(r)
	}
	return '?'
}

// pdfComplianceMatrixSection renders the compliance mapping table.
func pdfComplianceMatrixSection(doc *fpdf.Fpdf, d Data) {
	type compKey struct {
		standard string
		section  string
	}
	type compRow struct {
		standard string
		section  string
		title    string
		count    int
	}
	compMap := make(map[compKey]*compRow)
	var compKeys []compKey
	for _, f := range d.Findings {
		for _, c := range f.Compliance {
			k := compKey{standard: c.Standard, section: c.Section}
			row, exists := compMap[k]
			if !exists {
				row = &compRow{
					standard: c.Standard,
					section:  c.Section,
					title:    c.Title,
				}
				compMap[k] = row
				compKeys = append(compKeys, k)
			}
			row.count++
		}
	}
	if len(compKeys) == 0 {
		return
	}
	pdfSectionHeading(doc, "Compliance & Audit Matrix")
	cols := []pdfColumn{
		{Text: "Standard", Width: 25},
		{Text: "Section", Width: 25},
		{Text: "Benchmark Requirement", Width: 110},
		{Text: "Findings", Width: 20},
	}
	pdfTableHeader(doc, cols, pdfTableLineHMm)
	doc.SetFont(pdfFontFamily, "", 8)
	doc.SetTextColor(45, 45, 45)
	for _, k := range compKeys {
		r := compMap[k]
		pdfTableRow(doc, []pdfColumn{
			{Text: r.standard, Width: 25},
			{Text: r.section, Width: 25},
			{Text: r.title, Width: 110},
			{Text: fmt.Sprintf("%d", r.count), Width: 20},
		}, pdfTableLineHMm, false)
	}
	doc.Ln(4)
}

// pdfFindingsTable renders the top findings table, most severe first.
func pdfFindingsTable(doc *fpdf.Fpdf, d Data) {
	pdfSectionHeading(doc, "Findings")
	cols := []pdfColumn{
		{Text: "Severity", Width: 25},
		{Text: "Host:Port", Width: 45},
		{Text: "Title / CVE", Width: 80},
		{Text: "Status", Width: 30},
	}
	pdfTableHeader(doc, cols, pdfTableLineHMm)
	doc.SetFont(pdfFontFamily, "", 8)
	doc.SetTextColor(45, 45, 45)
	findings := sortedFindings(d.Findings)
	if len(findings) == 0 {
		pdfTableRow(doc, []pdfColumn{
			{Text: "No findings recorded.", Width: pdfUsableWidthMm},
		}, pdfTableLineHMm, false)
		doc.Ln(4)
		return
	}
	for _, f := range findings {
		title := f.Title
		if f.CVE != "" {
			title += " (" + f.CVE + ")"
		}
		pdfTableRow(doc, []pdfColumn{
			{Text: string(f.Severity), Width: 25},
			{Text: endpointText(f.Address, f.Port), Width: 45},
			{Text: title, Width: 80},
			{Text: string(f.Status), Width: 30},
		}, pdfTableLineHMm, false)
	}
	doc.Ln(4)
}

// pdfScreenshotsSection embeds captured login/session frames after remediation.
func pdfScreenshotsSection(doc *fpdf.Fpdf, d Data) {
	screens := reportScreens(d.Screens)
	if len(screens) == 0 {
		return
	}
	doc.AddPage()
	pdfSectionHeading(doc, "Screenshots")
	doc.SetFont(pdfFontFamily, "", 9)
	doc.SetTextColor(60, 60, 60)
	pdfParagraph(doc, fmt.Sprintf("%d captured frame(s). Synthetic detection cards are omitted.", len(screens)), pdfBodyLineHMm)
	doc.Ln(2)

	for i, s := range screens {
		caption := endpointText(s.Address, s.Port) + " · " + screenshotLabel(s.Username)
		if !s.CapturedAt.IsZero() {
			caption += " · " + formatTime(s.CapturedAt)
		}
		data, imageType, err := loadScreenshotBytes(s.FilePath)
		if err != nil {
			pdfParagraph(doc, caption+" — image unavailable ("+s.FilePath+")", pdfBodyLineHMm)
			doc.Ln(2)
			continue
		}
		name := fmt.Sprintf("shot-%d", i)
		opts := fpdf.ImageOptions{ImageType: imageType, ReadDpi: true}
		info := doc.RegisterImageOptionsReader(name, opts, bytes.NewReader(data))
		if info == nil || doc.Error() != nil {
			return
		}
		// Fit within page width; leave room for caption + margins.
		imgW := pdfUsableWidthMm
		imgH := imgW * info.Height() / info.Width()
		if imgH <= 0 {
			imgH = 80
		}
		maxH := pdfBreakY(doc) - doc.GetY() - 18
		if maxH < 40 {
			doc.AddPage()
			maxH = pdfBreakY(doc) - doc.GetY() - 18
		}
		if imgH > maxH {
			scale := maxH / imgH
			imgW *= scale
			imgH = maxH
		}
		needed := 8 + imgH + 4
		if doc.GetY()+needed > pdfBreakY(doc) {
			doc.AddPage()
		}
		doc.SetFont(pdfFontFamily, "B", 9)
		doc.SetTextColor(33, 47, 61)
		doc.MultiCell(pdfUsableWidthMm, pdfHeadingLineHMm, pdfText(caption), "", "L", false)
		doc.ImageOptions(name, pdfPageMarginMm, doc.GetY(), imgW, 0, false, opts, 0, "")
		doc.SetY(doc.GetY() + imgH + 4)
	}
}

// pdfRemediationSection lists every finding's remediation guidance.
func pdfRemediationSection(doc *fpdf.Fpdf, d Data) {
	pdfSectionHeading(doc, "Remediation")
	findings := sortedFindings(d.Findings)
	if len(findings) == 0 {
		pdfParagraph(doc, "No findings recorded.", pdfBodyLineHMm)
		return
	}
	for _, f := range findings {
		heading := fmt.Sprintf("[%s] %s - %s", f.CheckID, f.Title, endpointText(f.Address, f.Port))
		body := strings.TrimSpace(f.Remediation)
		if body == "" {
			body = "No remediation guidance recorded."
		}
		if len(f.Compliance) > 0 {
			var compParts []string
			for _, c := range f.Compliance {
				compParts = append(compParts, c.Standard+" "+c.Section)
			}
			body += "\nCompliance Benchmarks: " + strings.Join(compParts, " | ")
		}
		pdfRemediationEntry(doc, heading, body)
	}
}

// pdfRemediationEntry renders one heading plus wrapped body text. It starts a
// new page when the heading would be orphaned at the bottom margin; longer
// bodies flow across pages through MultiCell's automatic page breaks.
func pdfRemediationEntry(doc *fpdf.Fpdf, heading, body string) {
	headingLines := pdfWrapLines(doc, pdfText(heading), pdfUsableWidthMm)
	bodyLines := pdfWrapLines(doc, pdfText(body), pdfUsableWidthMm)
	needed := float64(len(headingLines))*pdfHeadingLineHMm + 2*pdfBodyLineHMm
	if doc.GetY()+needed > pdfBreakY(doc) {
		doc.AddPage()
	}
	doc.SetFont(pdfFontFamily, "B", 9.5)
	doc.SetTextColor(33, 47, 61)
	doc.MultiCell(pdfUsableWidthMm, pdfHeadingLineHMm, strings.Join(headingLines, "\n"), "", "L", false)
	doc.SetFont(pdfFontFamily, "", 9)
	doc.SetTextColor(60, 60, 60)
	doc.MultiCell(pdfUsableWidthMm, pdfBodyLineHMm, strings.Join(bodyLines, "\n"), "", "L", false)
	doc.Ln(2)
}

// pdfParagraph renders a short wrapped paragraph.
func pdfParagraph(doc *fpdf.Fpdf, text string, lineH float64) {
	doc.SetFont(pdfFontFamily, "", 9)
	doc.SetTextColor(60, 60, 60)
	lines := pdfWrapLines(doc, pdfText(text), pdfUsableWidthMm)
	doc.MultiCell(pdfUsableWidthMm, lineH, strings.Join(lines, "\n"), "", "L", false)
}


package reporter

import (
	"fmt"
	"io"
	"time"

	"github.com/go-pdf/fpdf"

	"rdpshot/internal/about"
	"rdpshot/internal/model"
)

const (
	comparePDFReportTitle = "RDP Executive Delta Assessment"
)

// ComparePDF writes an executive comparison PDF report analyzing differences
// between two scans (base vs against).
func ComparePDF(w io.Writer, diff model.ScanDiff, toolVersion string) error {
	doc := fpdf.New("P", "mm", "A4", "")
	doc.SetMargins(pdfPageMarginMm, pdfPageMarginMm, pdfPageMarginMm)
	doc.SetAutoPageBreak(true, pdfBottomMarginMm)
	doc.SetCellMargin(pdfCellMarginMm)
	doc.SetTitle(comparePDFReportTitle, false)
	doc.SetAuthor(about.Developer, false)
	doc.SetCreator(toolName, false)
	doc.AliasNbPages(pdfPageAlias)

	headerRight := fmt.Sprintf("%s vs %s", orDash(diff.BaseName), orDash(diff.AgainstName))
	footerLabel := "Generated by " + toolName
	if toolVersion != "" {
		footerLabel += " " + toolVersion
	}
	footerLabel += " · " + about.Developer
	footerLabel += " | Page %d of " + pdfPageAlias

	doc.SetHeaderFunc(func() { pdfPageHeader(doc, headerRight) })
	doc.SetFooterFunc(func() {
		pdfPageFooter(doc, fmt.Sprintf(footerLabel, doc.PageNo()))
	})

	doc.AddPage()
	pdfCompareTitleBlock(doc, diff)
	pdfCompareMetadataTable(doc, diff, toolVersion)
	pdfCompareKPICards(doc, diff)
	pdfCompareExecutiveNarrative(doc, diff)
	pdfCompareRemediatedSection(doc, diff)
	pdfCompareAddedSection(doc, diff)
	pdfCompareHostsSection(doc, diff)

	if err := doc.Error(); err != nil {
		return fmt.Errorf("build compare pdf report: %w", err)
	}
	if err := doc.Output(w); err != nil {
		return fmt.Errorf("write compare pdf report: %w", err)
	}
	return nil
}

func pdfCompareTitleBlock(doc *fpdf.Fpdf, diff model.ScanDiff) {
	doc.SetFont(pdfFontFamily, "B", 18)
	doc.SetTextColor(33, 47, 61)
	doc.CellFormat(0, 10, pdfText("Executive Delta Comparison Report"), "", 1, "L", false, 0, "")
	subtitle := fmt.Sprintf("Comparative Security Posture: %s  vs  %s", orDash(diff.BaseName), orDash(diff.AgainstName))
	doc.SetFont(pdfFontFamily, "", 10)
	doc.SetTextColor(100, 100, 100)
	doc.CellFormat(0, 7, pdfText(subtitle), "", 1, "L", false, 0, "")
	doc.Ln(2)
}

func pdfCompareMetadataTable(doc *fpdf.Fpdf, diff model.ScanDiff, toolVersion string) {
	pdfSectionHeading(doc, "Comparison Scope & Metadata")
	rows := [][2]string{
		{"Base Audit (Prior)", fmt.Sprintf("%s (%s)", orDash(diff.BaseName), orDash(diff.BaseID))},
		{"Against Audit (Current)", fmt.Sprintf("%s (%s)", orDash(diff.AgainstName), orDash(diff.AgainstID))},
		{"Generated At", time.Now().UTC().Format("2006-01-02 15:04:05 UTC")},
		{"Engine Version", orDash(toolVersion)},
	}
	for _, row := range rows {
		pdfTableRow(doc, []pdfColumn{
			{Text: row[0], Width: 55},
			{Text: row[1], Width: pdfUsableWidthMm - 55},
		}, pdfTableLineHMm, false)
	}
	doc.Ln(4)
}

func pdfCompareKPICards(doc *fpdf.Fpdf, diff model.ScanDiff) {
	pdfSectionHeading(doc, "Delta Key Performance Indicators")

	cardW := (pdfUsableWidthMm - 9.0) / 4.0 // 4 cards with 3mm gap
	cardH := 18.0
	y := doc.GetY()

	cards := []struct {
		Label string
		Value string
		Color [3]int
	}{
		{
			Label: "Hardening Score",
			Value: formatDeltaScore(diff.Summary.HardeningScoreDelta),
			Color: scoreColor(diff.Summary.HardeningScoreDelta),
		},
		{
			Label: "Remediated Vulns",
			Value: fmt.Sprintf("%d Resolved", diff.Summary.FindingsRemediated),
			Color: [3]int{16, 149, 106}, // emerald
		},
		{
			Label: "New Findings",
			Value: fmt.Sprintf("%d Introduced", diff.Summary.FindingsAdded),
			Color: [3]int{225, 29, 72}, // rose
		},
		{
			Label: "Host Movement",
			Value: fmt.Sprintf("+%d / -%d", diff.Summary.HostsAdded, diff.Summary.HostsRemoved),
			Color: [3]int{79, 70, 229}, // indigo
		},
	}

	for i, c := range cards {
		x := pdfPageMarginMm + float64(i)*(cardW+3.0)
		// Card background
		doc.SetFillColor(248, 250, 252)
		doc.SetDrawColor(226, 232, 240)
		doc.SetLineWidth(0.2)
		doc.Rect(x, y, cardW, cardH, "FD")

		// Value
		doc.SetXY(x, y+2.5)
		doc.SetFont(pdfFontFamily, "B", 11)
		doc.SetTextColor(c.Color[0], c.Color[1], c.Color[2])
		doc.CellFormat(cardW, 6, pdfText(c.Value), "", 1, "C", false, 0, "")

		// Label
		doc.SetX(x)
		doc.SetFont(pdfFontFamily, "", 7.5)
		doc.SetTextColor(100, 116, 139)
		doc.CellFormat(cardW, 5, pdfText(c.Label), "", 1, "C", false, 0, "")
	}

	doc.SetY(y + cardH + 5)
}

func formatDeltaScore(delta int) string {
	if delta > 0 {
		return fmt.Sprintf("+%d pts", delta)
	}
	if delta < 0 {
		return fmt.Sprintf("%d pts", delta)
	}
	return "0 pts (Neutral)"
}

func scoreColor(delta int) [3]int {
	if delta > 0 {
		return [3]int{16, 149, 106} // emerald
	}
	if delta < 0 {
		return [3]int{225, 29, 72} // rose
	}
	return [3]int{100, 116, 139} // slate
}

func pdfCompareExecutiveNarrative(doc *fpdf.Fpdf, diff model.ScanDiff) {
	pdfSectionHeading(doc, "Executive Summary & Posture Verdict")

	var verdict string
	delta := diff.Summary.HardeningScoreDelta
	remediated := diff.Summary.FindingsRemediated
	added := diff.Summary.FindingsAdded

	switch {
	case delta > 0 || (remediated > 0 && added == 0):
		verdict = fmt.Sprintf("POSITIVE REMEDIATION: The target environment demonstrates measurable security posture improvements. A total of %d vulnerability instances have been remediated or verified closed since the base assessment, resulting in a hardening score delta of %s.", remediated, formatDeltaScore(delta))
	case delta < 0 || added > remediated:
		verdict = fmt.Sprintf("POSTURE REGRESSION / ELEVATED RISK: The comparison indicates an increase in security exposure. %d new finding(s) were identified while %d finding(s) were remediated. Net hardening score shifted by %s.", added, remediated, formatDeltaScore(delta))
	default:
		verdict = "STABLE POSTURE: No significant security posture deviation was detected between the assessed periods. Host count and exposure parameters remained consistent across both evaluation cycles."
	}

	doc.SetFont(pdfFontFamily, "", 8.5)
	doc.SetTextColor(45, 55, 72)
	lines := pdfWrapLines(doc, verdict, pdfUsableWidthMm)
	for _, l := range lines {
		doc.CellFormat(pdfUsableWidthMm, 5, pdfText(l), "", 1, "L", false, 0, "")
	}
	doc.Ln(4)
}

func pdfCompareRemediatedSection(doc *fpdf.Fpdf, diff model.ScanDiff) {
	if len(diff.FindingsRemoved) == 0 {
		return
	}
	pdfSectionHeading(doc, fmt.Sprintf("Remediated Findings (%d Resolved)", len(diff.FindingsRemoved)))
	cols := []pdfColumn{
		{Text: "Target Endpoint", Width: 45},
		{Text: "Severity", Width: 25},
		{Text: "Finding Title / Vulnerability", Width: 85},
		{Text: "Status", Width: 25},
	}
	pdfTableHeader(doc, cols, pdfTableLineHMm)
	doc.SetFont(pdfFontFamily, "", 8)

	for _, f := range diff.FindingsRemoved {
		ep := fmt.Sprintf("%s:%d", f.Address, f.Port)
		pdfTableRow(doc, []pdfColumn{
			{Text: ep, Width: 45},
			{Text: string(f.Severity), Width: 25},
			{Text: f.Title, Width: 85},
			{Text: "Resolved", Width: 25},
		}, pdfTableLineHMm, false)
	}
	doc.Ln(4)
}

func pdfCompareAddedSection(doc *fpdf.Fpdf, diff model.ScanDiff) {
	if len(diff.FindingsAdded) == 0 {
		return
	}
	pdfSectionHeading(doc, fmt.Sprintf("Newly Introduced Findings (%d New)", len(diff.FindingsAdded)))
	cols := []pdfColumn{
		{Text: "Target Endpoint", Width: 45},
		{Text: "Severity", Width: 25},
		{Text: "Finding Title / Risk", Width: 85},
		{Text: "Status", Width: 25},
	}
	pdfTableHeader(doc, cols, pdfTableLineHMm)
	doc.SetFont(pdfFontFamily, "", 8)

	for _, f := range diff.FindingsAdded {
		ep := fmt.Sprintf("%s:%d", f.Address, f.Port)
		pdfTableRow(doc, []pdfColumn{
			{Text: ep, Width: 45},
			{Text: string(f.Severity), Width: 25},
			{Text: f.Title, Width: 85},
			{Text: string(f.Status), Width: 25},
		}, pdfTableLineHMm, false)
	}
	doc.Ln(4)
}

func pdfCompareHostsSection(doc *fpdf.Fpdf, diff model.ScanDiff) {
	totalHostChanges := len(diff.HostsAdded) + len(diff.HostsRemoved) + len(diff.HostsChanged)
	if totalHostChanges == 0 {
		return
	}
	pdfSectionHeading(doc, "Host Infrastructure & Exposure Delta")
	cols := []pdfColumn{
		{Text: "Target Endpoint", Width: 45},
		{Text: "Movement / Delta", Width: 35},
		{Text: "Details", Width: 100},
	}
	pdfTableHeader(doc, cols, pdfTableLineHMm)
	doc.SetFont(pdfFontFamily, "", 8)

	for _, h := range diff.HostsAdded {
		ep := fmt.Sprintf("%s:%d", h.Endpoint.Address, h.Endpoint.Port)
		pdfTableRow(doc, []pdfColumn{
			{Text: ep, Width: 45},
			{Text: "Added / Discovered", Width: 35},
			{Text: fmt.Sprintf("State: %s", h.State), Width: 100},
		}, pdfTableLineHMm, false)
	}
	for _, h := range diff.HostsRemoved {
		ep := fmt.Sprintf("%s:%d", h.Endpoint.Address, h.Endpoint.Port)
		pdfTableRow(doc, []pdfColumn{
			{Text: ep, Width: 45},
			{Text: "Removed / Offline", Width: 35},
			{Text: fmt.Sprintf("Prior State: %s", h.State), Width: 100},
		}, pdfTableLineHMm, false)
	}
	for _, c := range diff.HostsChanged {
		ep := fmt.Sprintf("%s:%d", c.Address, c.Port)
		details := fmt.Sprintf("NLA: %v -> %v, TLS: %s -> %s", c.Before.NLARequired, c.After.NLARequired, c.Before.TLSVersion, c.After.TLSVersion)
		pdfTableRow(doc, []pdfColumn{
			{Text: ep, Width: 45},
			{Text: "Posture Changed", Width: 35},
			{Text: details, Width: 100},
		}, pdfTableLineHMm, false)
	}
	doc.Ln(4)
}
